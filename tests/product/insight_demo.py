"""Export a concrete synthetic CP6 result from actual CP4/CP5 source replays.

Run from the repository: python -m tests.product.insight_demo --output /tmp/NEW_DIR.
This is a test/evidence tool, never a real-source admission or personal preference.
"""
import argparse
import datetime as dt
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from insight_service.service import compute_insights, reproduce_insights
from insight_service.sources import verify_source
from insights.contracts import HistoryComparison, InsightResult, MetricRef
from marketdata.canonical import sha256_hex
from tests.product.insight_testkit import cp4_source, cp5_source
from tests.product.test_insight_integration import policy_for


def build_demo():
    risk, *_ = cp4_source()
    fresh, *_ = cp5_source(with_freshness=True)
    current, *_ = cp5_source(prefix="P11 ")
    baseline, *_ = cp5_source(prefix="P11 ", as_of=dt.date(2025, 9, 26))
    ce, be = (verify_source(s, allow_synthetic=True) for s in (current, baseline))
    history = (HistoryComparison(MetricRef(ce.source_id, "hhi_concentration"), MetricRef(be.source_id, "hhi_concentration")),)
    policies = (policy_for(fresh), policy_for(current, "sector_exposure", ("EXPLICIT_SYNTHETIC_SECTOR",)))
    sources = (risk, fresh, current, baseline)
    result = compute_insights(sources, policies=policies, history=history, allow_synthetic=True)
    if not isinstance(result, InsightResult):
        raise ValueError(result)
    report = reproduce_insights(result, result.result_digest, sources, policies=policies, history=history, allow_synthetic=True)
    if report.status != "REPRODUCED":
        raise ValueError(report)
    return result, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    result, report = build_demo()
    summary = {"label": "SYNTHETIC ONLY — no real personal limit or real-data claim", "method": "insights/1.0",
               "manifest_id": result.manifest_id, "result_digest": result.result_digest, "reproduction": report.status,
               "packets": [{"insight_id": p.insight_id, "rule": p.to_obj()["insight_type"], "class": p.to_obj()["judgment_class"],
                            "severity": p.to_obj()["severity"], "claim": p.to_obj()["claim"]["text"]} for p in result.packets],
               "limitations": ["Four bounded families, actual engine source adapters, synthetic fixture inputs", "HG3 66 gaps remain explicit; this export does not close them"]}
    files = {"result.json": result.canonical_json() + "\n", "summary.json": json.dumps(summary, ensure_ascii=False, sort_keys=True, indent=2) + "\n",
             "README.md": "# CP6 synthetic rule evidence\n\nGenerated by `python -m tests.product.insight_demo --output /tmp/NEW_DIR`.\n\n"
                          "`summary.json` lists the actual generated claims. `result.json` contains complete immutable Proof Packets, upstream manifests and results, "
                          "exact witnesses, policies, freshness auxiliary, comparison inputs and reproducible digests. The exporter replayed those actual sources and obtained REPRODUCED.\n\n"
                          "The example personal limits are SYNTHETIC. They are not the owner's investment preferences. The FULL_NAV product denominator is the recorded PD-0041 choice. "
                          "Missing freshness caps applicable user-limit claims at Attention; the matching verified CP3 valuation supplies the separate full-freshness Warning example. "
                          "Observation/retrieval timestamps not present upstream remain UNKNOWN. This is neither a real-data certification nor HG5 approval.\n"}
    checksums = {}
    for name, contents in files.items():
        raw = contents.encode("utf-8")
        (args.output / name).write_bytes(raw)
        checksums[name] = sha256_hex(raw)
    (args.output / "FILES_SHA256.json").write_text(json.dumps(checksums, sort_keys=True, indent=2) + "\n", encoding="utf-8")
    print(json.dumps({"output": str(args.output.resolve()), "packets": len(result.packets), "rules": sorted({p.to_obj()["insight_type"] for p in result.packets}),
                      "severities": sorted({p.to_obj()["severity"] for p in result.packets}), "reproduction": report.status, "result_digest": result.result_digest}, sort_keys=True))


if __name__ == "__main__":
    main()
